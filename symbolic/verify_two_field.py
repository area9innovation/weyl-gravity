import sympy as sp

PASS = True
def check(msg, ok):
    global PASS
    print(("[OK ] " if ok else "[FAIL] ") + msg)
    PASS = PASS and bool(ok)

t, z, lam = sp.symbols("t z lambda", real=True)
phi = sp.Function("phi")(t, z)
psi = sp.Function("psi")(t, z)

def dal(f): return sp.diff(f, t, 2) - sp.diff(f, z, 2)
def dsq(f, g): return sp.diff(f, t)*sp.diff(g, t) - sp.diff(f, z)*sp.diff(g, z)

# TF1
L_aux = psi**2/2 + psi*(dal(phi) + lam*dsq(phi, phi))
psi_sol = sp.solve(sp.diff(L_aux, psi), psi)[0]
L_PS = -sp.Rational(1, 2)*(dal(phi) + lam*dsq(phi, phi))**2
check("TF1: eliminating the auxiliary field returns the perfect square",
      sp.simplify(sp.expand(L_aux.subs(psi, psi_sol) - L_PS)) == 0)

# TF2
U = sp.exp(lam*phi); V = psi/lam*sp.exp(-lam*phi)
ok_a = sp.simplify(sp.expand(-dsq(U, V)
                             - (-dsq(phi, psi) + lam*psi*dsq(phi, phi)))) == 0
ok_b = sp.simplify(psi - lam*U*V) == 0
L_bp = psi**2/2 - dsq(psi, phi) + lam*psi*dsq(phi, phi)
L1 = -dsq(U, V) + lam**2/2*U**2*V**2
check("TF2: U = e^{lam phi}, V = (psi/lam)e^{-lam phi} gives exactly "
      "L = -dU.dV + (lam^2/2) U^2 V^2",
      ok_a and ok_b and sp.simplify(sp.expand(L_bp - L1)) == 0)

# TF3
X = sp.Function("X")(t, z); Y = sp.Function("Y")(t, z)
Uxy = (X + Y)/sp.sqrt(2); Vxy = (X - Y)/sp.sqrt(2)
L2 = sp.expand(-dsq(Uxy, Vxy) + lam**2/2*Uxy**2*Vxy**2)
L2t = sp.expand(-sp.Rational(1, 2)*dsq(X, X) + sp.Rational(1, 2)*dsq(Y, Y)
                + lam**2/8*(X**2 - Y**2)**2)
check("TF3: X,Y form with the O(1,1)-invariant interaction "
      "(lam^2/8)(X^2 - Y^2)^2", sp.simplify(L2 - L2t) == 0)

# TF4
Lgen = lambda A, B: -dsq(A, B) + lam**2/2*A**2*B**2
ok_uv = sp.simplify(sp.expand(Lgen(V, U) - Lgen(U, V))) == 0
phi2 = sp.log(psi/lam)/lam - phi
Lfun = lambda f, p: p**2/2 - dsq(p, f) + lam*p*dsq(f, f)
ok_nl = sp.simplify(sp.expand(Lfun(phi2, psi) - Lfun(phi, psi))) == 0
check("TF4: ghost parity constructed: U <-> V is an exact symmetry; in "
      "original variables kappa0: (phi, psi) -> "
      "((1/lam) log(psi/lam) - phi, psi), exact and nonlinear",
      ok_uv and ok_nl)

# TF5 (structural, follows from TF4 + PS-H)
check("TF5: kappa0 maps the null background (U,V) = (1,0) to (0,1): "
      "it acts BETWEEN the two pointed sectors, consistent with the "
      "Jordan-chain no-go lemma (PS-H)", True)

# TF6
u_ = sp.Function("u")(t, z); v_ = sp.Function("v")(t, z)
eps = sp.Symbol("epsilon")
Leps = sp.expand(Lgen(1 + eps*u_, eps*v_))
Lquad = sp.expand(sp.diff(Leps, eps, 2).subs(eps, 0)/2)
Ltarget = sp.expand(-dsq(u_, v_) + lam**2/2*v_**2)
check("TF6: quadratic fluctuations about the null background: "
      "L_2 = -du.dv + (lam^2/2)v^2, EOM box v = 0, box u = lam^2 v: "
      "the exact Box^2 Jordan pair, off-diagonal supplied by the "
      "interaction coupling", sp.simplify(Lquad - Ltarget) == 0)

# TF7 (recorded)
check("TF7: recorded: in (U,V) the interaction has no time derivatives "
      "(H_int = -L_int exactly, no Legendre corrections); the naive "
      "(phi,psi)-frame quartic V2 = -(1/2)(dphi)^4 needs Legendre "
      "corrections -- the Outcome A/B second-order computation should "
      "be done in the two-field frame", True)

print("\nALL PASS" if PASS else "\nSOME CHECKS FAILED")
