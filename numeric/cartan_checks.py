#!/usr/bin/env python3
"""Regression checks for Section 2.3 of paper 2 (orthogonal Cartan-norm
projection principle).

1. Canonical hull (Prop. hull): dim_R of the real Lie algebra generated by
   h_j = C X_j and theta(h_j) = C X_j^dag is 6 = dim sl(2,C) per mode for
   omega_j != 1, and 2 = dim so(2,C) at the exceptional value omega_j = 1.
2. Normal space: the Hermitian Hamiltonian inter-mode couplings form a
   4-dim space containing B, trace-orthogonal to the mode-diagonal
   Hermitian Hamiltonians (6-dim);  6 + 4 = 10 = dim p.
3. First variation (Thm. projection (a)):
   d/dt F(e^xi e^{t eta})|_0 = 8 tr(eta xi)  for eta mode-diagonal,
   xi arbitrary Hermitian Hamiltonian.  This is the engine of the
   if-and-only-if characterization (c).
"""

import numpy as np
from scipy.linalg import expm

TOL = 1e-6
J = np.zeros((4, 4)); J[0, 2] = J[1, 3] = 1; J[2, 0] = J[3, 1] = -1
sig = [np.array([[0, 1], [1, 0]], complex), np.array([[0, -1j], [1j, 0]], complex),
       np.array([[1, 0], [0, -1]], complex)]


def lie_closure_dim_real(gens, tol=1e-9):
    basis = []

    def tovec(M):
        return np.concatenate([M.real.flatten(), M.imag.flatten()])

    def add(M):
        v = tovec(M)
        for b in basis:
            v = v - np.dot(b, v) * b
        n = np.linalg.norm(v)
        if n > tol:
            basis.append(v / n)
            return True
        return False

    mats = []
    for g in gens:
        if add(g):
            mats.append(g)
    changed = True
    while changed:
        changed = False
        cur = list(mats)
        for A in cur:
            for B in cur:
                M = A @ B - B @ A
                if add(M):
                    mats.append(M)
                    changed = True
    return len(basis)


def embed(blk, idx):
    M = np.zeros((4, 4), complex)
    M[np.ix_(idx, idx)] = blk
    return M


def main():
    ok = True

    # 1) canonical hull
    for w2, expect in [(1.7, 6), (0.4, 6), (2.0 / 1.3, 6), (1.0, 2)]:
        X1 = np.array([[0, w2], [-1 / w2, 0]], dtype=complex)
        gens = [X1, 1j * X1, -X1.conj().T, -(1j * X1).conj().T]
        d = lie_closure_dim_real(gens)
        good = d == expect
        ok &= good
        print(f"[{'OK ' if good else 'FAIL'}] hull dim at w={w2:.3f}: {d} (expect {expect})")

    # 2) normal space
    CP = [embed(s, [0, 2]) for s in sig] + [embed(s, [1, 3]) for s in sig]
    OD = []
    for i in [0, 2]:
        for j in [1, 3]:
            for z in [1, 1j]:
                M = np.zeros((4, 4), complex)
                M[i, j] = z
                M[j, i] = np.conj(z)
                Mh = (M + J @ M.T @ J) / 2
                Mh = (Mh + Mh.conj().T) / 2
                if np.abs(Mh.T @ J + J @ Mh).max() < 1e-12 and np.linalg.norm(Mh) > 1e-8:
                    OD.append(Mh)
    # real-orthonormalize OD
    odb = []

    def tovec(M):
        return np.concatenate([M.real.flatten(), M.imag.flatten()])

    for M in OD:
        v = tovec(M)
        for b, _ in odb:
            v = v - np.dot(b, v) * b
        n = np.linalg.norm(v)
        if n > 1e-9:
            odb.append((v / n, M))
    OD = [m for _, m in odb]
    good = len(OD) == 4
    ok &= good
    print(f"[{'OK ' if good else 'FAIL'}] inter-mode Hermitian Hamiltonian space dim = {len(OD)} (expect 4)")

    B = np.zeros((4, 4), complex); B[0, 3] = 1j; B[1, 2] = 1j; B[2, 1] = -1j; B[3, 0] = -1j
    v = tovec(B)
    for b, _ in odb:
        v = v - np.dot(b, v) * b
    good = np.linalg.norm(v) < 1e-9
    ok &= good
    print(f"[{'OK ' if good else 'FAIL'}] B lies in the inter-mode space")

    good = max(abs(np.trace(m1 @ m2).real) for m1 in OD for m2 in CP) < 1e-12
    ok &= good
    print(f"[{'OK ' if good else 'FAIL'}] inter-mode space trace-orthogonal to mode-diagonal space")

    # 3) first variation
    def F_of(S):
        ev = np.linalg.eigvalsh(S.conj().T @ S)
        return float(np.sum(np.log(ev) ** 2))

    rng = np.random.default_rng(4)
    worst = 0.0
    for _ in range(8):
        xi = sum(rng.normal() * m for m in CP) * 0.3 + sum(rng.normal() * m for m in OD) * 0.5
        eta = sum(rng.normal() * m for m in CP) * 0.5
        t = 1e-6
        S0 = expm(xi)
        d_num = (F_of(S0 @ expm(t * eta)) - F_of(S0 @ expm(-t * eta))) / (2 * t)
        d_form = 8 * np.trace(eta @ xi).real
        worst = max(worst, abs(d_num - d_form) / max(1.0, abs(d_form)))
    good = worst < TOL
    ok &= good
    print(f"[{'OK ' if good else 'FAIL'}] first variation d/dt F = 8 tr(eta xi): worst rel err {worst:.2e}")

    # 4) normalization dictionary: F(g) = 2 |mu(g)|^2 ;  F(e^xi) = |2 xi|_F^2 ;
    #    min sqrt(F) = |2 xi|_F ;  min |mu| = |2 xi|_F / sqrt(2)
    for _ in range(4):
        xi = sum(rng.normal() * m for m in CP) * 0.3 + sum(rng.normal() * m for m in OD) * 0.5
        S = expm(xi)
        F = F_of(S)
        mu2 = sum(x ** 2 for x in np.log(np.linalg.eigvalsh(S.conj().T @ S))[2:])  # chamber half
        n2xi = 4 * np.linalg.norm(xi) ** 2
        good = abs(F - 2 * mu2) < 1e-8 * max(1, F) and abs(F - n2xi) < 1e-8 * max(1, F)
        ok &= good
        print(f"[{'OK ' if good else 'FAIL'}] dictionary: F={F:.6f}  2|mu|^2={2*mu2:.6f}  |2xi|^2={n2xi:.6f}")

    print("\nALL PASS" if ok else "\nSOME CHECKS FAILED")
    return ok


if __name__ == "__main__":
    main()
