Multiindex = tuple[int, int, int, int]
ZERO: Multiindex = (0, 0, 0, 0)


def _digest_matrix(matrix: sp.MatrixBase) -> str:
    return hashlib.sha256(
        sp.srepr(sp.ImmutableSparseMatrix(matrix)).encode("utf-8")
    ).hexdigest()


def _certificate_digest(certificate: Mapping[str, object]) -> str:
    return hashlib.sha256(
        json.dumps(
            certificate, sort_keys=True, separators=(",", ":")
        ).encode("utf-8")
    ).hexdigest()


def _nonzero_count(table: CoefficientTable) -> int:
    return sum(int(value != 0) for _, matrix in table for value in matrix)


def _table_formal_adjoint(table: CoefficientTable) -> CoefficientTable:
    return tuple(
        (
            multiindex,
            (((-1) ** sum(multiindex)) * coefficient.T).applyfunc(sp.expand),
        )
        for multiindex, coefficient in table
    )


def _sparse_table(
    table: CoefficientTable,
    *,
    source: str,
    target: str,
) -> dict[str, object]:
    rows, columns = table[0][1].shape
    return {
        "source": source,
        "target": target,
        "shape": [rows, columns],
        "maximum_order": max(sum(multiindex) for multiindex, _ in table),
        "coefficient_multiindices": len(table),
        "nonzero_coefficients": _nonzero_count(table),
        "sha256": _digest_tables(table),
        "coefficients": [
            {
                "multiindex": list(multiindex),
                "entries": [
                    [row, column, str(matrix[row, column])]
                    for row in range(rows)
                    for column in range(columns)
                    if matrix[row, column] != 0
                ],
            }
            for multiindex, matrix in table
        ],
    }


def _metric_gauge_table() -> CoefficientTable:
    """Return the complete curved ``K_met:(xi,sigma)->h`` table."""

    source = _ordinary_system()
    tables: list[tuple[Multiindex, sp.Matrix]] = []
    zeroth = sp.zeros(10, 5)
    zeroth[:, 4] = sp.Matrix(
        [source.metric[a, b] for a, b in SYMMETRIC_COORDINATES]
    )
    tables.append((ZERO, zeroth))
    for axis in range(4):
        coefficient = sp.zeros(10, 5)
        for ghost in range(4):
            for row, (a, b) in enumerate(SYMMETRIC_COORDINATES):
                coefficient[row, ghost] = int(axis == a and ghost == b) + int(
                    axis == b and ghost == a
                )
        multiindex = tuple(int(index == axis) for index in range(4))
        tables.append((multiindex, coefficient))
    return tuple(sorted(tables))


def _metric_bach_table(
    basis: CovariantJetBasis,
    bach: LinearizedBach,
    field_pairing: sp.Matrix,
) -> CoefficientTable:
    """Reconstruct ``J_met^-1 E_Bach`` on every covariant four-jet."""

    source = _ordinary_system()
    output: list[tuple[Multiindex, sp.Matrix]] = []
    for multiindex in basis.geometry.exhaustive_multiindices(4):
        raw = sp.zeros(10)
        for column in range(10):
            metric = basis.covariant_monomial_symmetric(
                column, multiindex, 4
            )
            image = bach.action_normalized_bach(metric)
            coordinates = sp.Matrix(
                [image[a][b].value for a, b in SYMMETRIC_COORDINATES]
            )
            raw[:, column] = source.tensor_pairing * coordinates
        output.append(
            (
                multiindex,
                (field_pairing.inv() * raw).applyfunc(sp.expand),
            )
        )
    return tuple(sorted(output))


def _metric_companion_table(
    gauge: CoefficientTable,
    field_pairing: sp.Matrix,
    ghost_pairing: sp.Matrix,
) -> CoefficientTable:
    """Define ``C_met=Y_met^-1 K_met^sharp J_met`` coefficientwise."""

    return tuple(
        (
            multiindex,
            (
                ghost_pairing.inv()
                * ((-1) ** sum(multiindex) * coefficient.T)
                * field_pairing
            ).applyfunc(sp.expand),
        )
        for multiindex, coefficient in gauge
    )


def _shift_metric_from_projection(
    projection: CoefficientTable, field_pairing: sp.Matrix
) -> CoefficientTable:
    """Recover ``S_h`` from ``p_E=(J^-1 S_h^sharp J,1,0)``."""

    inverse = field_pairing.inv()
    return tuple(
        (
            multiindex,
            (
                (-1) ** sum(multiindex)
                * inverse
                * coefficient[:, :10].T
                * field_pairing
            ).applyfunc(sp.expand),
        )
        for multiindex, coefficient in projection
    )


@dataclass(frozen=True)
class ProlongedMetricEndpointComplex:
    """Coefficient-complete local presentation of the retained endpoint."""

    covector: tuple[sp.Symbol, ...]
    field_pairing: sp.Matrix
    ghost_pairing: sp.Matrix
    gauge_coefficients: CoefficientTable
    bach_coefficients: CoefficientTable
    companion_coefficients: CoefficientTable
    shift_metric_coefficients: CoefficientTable
    state_graph_coefficients: CoefficientTable
    equation_graph_coefficients: CoefficientTable
    identity_graph_coefficients: CoefficientTable
    equation_projection_coefficients: CoefficientTable
    identity_projection_coefficients: CoefficientTable

    @staticmethod
    def build() -> "ProlongedMetricEndpointComplex":
        basis = CovariantJetBasis.build()
        source = _ordinary_system()
        core = CurvedCoreCurvatureChainMap.build()
        field_pairing = source.field_fibre_pairing[:10, 10:20]
        ghost_pairing = source.gauge_fixing_pairing.extract(
            [0, 1, 2, 3, 8], [4, 5, 6, 7, 8]
        )

        gauge = _metric_gauge_table()
        bach = _metric_bach_table(
            basis, LinearizedBach.build(), field_pairing
        )
        companion = _metric_companion_table(
            gauge, field_pairing, ghost_pairing
        )
        shift_metric = _shift_metric_from_projection(
            core.equation_projection_coefficients, field_pairing
        )

        # This is the exhaustive curved state map (C1 h, div C1 h), not the
        # later principal-only rank-14 symbol audit.
        state_full = _state_coefficient_chunk(
            tuple(basis.geometry.exhaustive_multiindices(3))
        )
        state = tuple(
            (multiindex, coefficient[:, :10])
            for multiindex, coefficient in state_full
        )
        equation = ((ZERO, core.core_equation_attachment),)
        identity = ((ZERO, core.core_identity_attachment),)

        result = ProlongedMetricEndpointComplex(
            covector=basis.covector,
            field_pairing=field_pairing,
            ghost_pairing=ghost_pairing,
            gauge_coefficients=gauge,
            bach_coefficients=bach,
            companion_coefficients=companion,
            shift_metric_coefficients=shift_metric,
            state_graph_coefficients=state,
            equation_graph_coefficients=equation,
            identity_graph_coefficients=identity,
            equation_projection_coefficients=(
                core.equation_projection_coefficients
            ),
            identity_projection_coefficients=(
                core.identity_projection_coefficients
            ),
        )
        result.verify()
        return result

    @staticmethod
    def from_coefficient_payload(
        payload: Mapping[str, object],
    ) -> "ProlongedMetricEndpointComplex":
        """Load the content-addressed fast rail without rerunning 1,050 jets.

        The exhaustive :meth:`build` rail is the authority which emits the
        payload.  This loader reconstructs every rational matrix from that
        payload and reruns the algebraic coverage, adjoint, and cyclicity
        checks.  It deliberately does not claim to be a second derivation of
        the curved coefficients.
        """

        if payload.get("schema") != (
            "pure-weyl-prolonged-metric-endpoint-coefficients-v1"
        ):
            raise AssertionError("wrong endpoint coefficient payload schema")

        def table(section: Mapping[str, object], name: str) -> CoefficientTable:
            value = section.get(name)
            if not isinstance(value, Mapping):
                raise AssertionError(f"missing coefficient table {name}")
            shape = value.get("shape")
            coefficients = value.get("coefficients")
            if not (
                isinstance(shape, list)
                and len(shape) == 2
                and all(isinstance(entry, int) for entry in shape)
                and isinstance(coefficients, list)
            ):
                raise AssertionError(f"malformed coefficient table {name}")
            output: list[tuple[Multiindex, sp.Matrix]] = []
            for item in coefficients:
                if not isinstance(item, Mapping):
                    raise AssertionError(f"malformed coefficient item in {name}")
                multiindex_value = item.get("multiindex")
                entries = item.get("entries")
                if not (
                    isinstance(multiindex_value, list)
                    and len(multiindex_value) == 4
                    and all(isinstance(entry, int) for entry in multiindex_value)
                    and isinstance(entries, list)
                ):
                    raise AssertionError(f"malformed coefficient item in {name}")
                matrix = sp.zeros(shape[0], shape[1])
                for entry in entries:
                    if not isinstance(entry, list) or len(entry) != 3:
                        raise AssertionError(f"malformed sparse entry in {name}")
                    row, column, coefficient = entry
                    matrix[row, column] = sp.Rational(coefficient)
                output.append((tuple(multiindex_value), matrix))
            result = tuple(output)
            if _digest_tables(result) != value.get("sha256"):
                raise AssertionError(f"coefficient digest mismatch in {name}")
            return result

        endpoint = payload.get("endpoint_Q")
        graph = payload.get("graph_inclusion_primal")
        projection = payload.get("base_projection")
        pairings = payload.get("pairings")
        if not all(
            isinstance(value, Mapping)
            for value in (endpoint, graph, projection, pairings)
        ):
            raise AssertionError("endpoint coefficient payload is incomplete")
        assert isinstance(endpoint, Mapping)
        assert isinstance(graph, Mapping)
        assert isinstance(projection, Mapping)
        assert isinstance(pairings, Mapping)
        field_pairing = sp.Matrix(
            10, 10, [sp.Rational(value) for value in pairings["J_met"]]
        )
        ghost_pairing = sp.Matrix(
            5, 5, [sp.Rational(value) for value in pairings["Y_met"]]
        )
        if _digest_matrix(field_pairing) != pairings.get("J_met_sha256"):
            raise AssertionError("endpoint field-pairing digest mismatch")
        if _digest_matrix(ghost_pairing) != pairings.get("Y_met_sha256"):
            raise AssertionError("endpoint ghost-pairing digest mismatch")

        result = ProlongedMetricEndpointComplex(
            covector=tuple(sp.symbols("endpoint_cache_zeta_0:4", real=True)),
            field_pairing=field_pairing,
            ghost_pairing=ghost_pairing,
            gauge_coefficients=table(endpoint, "K_met"),
            bach_coefficients=table(endpoint, "Bach_bar"),
            companion_coefficients=table(endpoint, "C_met"),
            shift_metric_coefficients=table(graph, "S_h"),
            state_graph_coefficients=table(graph, "T_core"),
            equation_graph_coefficients=table(graph, "A_core"),
            identity_graph_coefficients=table(graph, "B_core"),
            equation_projection_coefficients=table(projection, "p_E"),
            identity_projection_coefficients=table(projection, "p_I"),
        )
        result.verify()
        return result

    def verify(self) -> None:
        expected = {
            "K_met": (self.gauge_coefficients, (10, 5), 5, 1),
            "Bach_bar": (self.bach_coefficients, (10, 10), 70, 4),
            "C_met": (self.companion_coefficients, (5, 10), 5, 1),
            "S_h": (self.shift_metric_coefficients, (10, 10), 15, 2),
            "T_core": (self.state_graph_coefficients, (26, 10), 35, 3),
            "A_core": (self.equation_graph_coefficients, (40, 10), 1, 0),
            "B_core": (self.identity_graph_coefficients, (14, 5), 1, 0),
            "p_E": (
                self.equation_projection_coefficients,
                (10, 24),
                15,
                2,
            ),
            "p_I": (
                self.identity_projection_coefficients,
                (5, 9),
                5,
                1,
            ),
        }
        for name, (table, shape, count, maximum_order) in expected.items():
            if len(table) != count or any(
                matrix.shape != shape for _, matrix in table
            ):
                raise AssertionError(f"{name} coefficient coverage drifted")
            if max(sum(multiindex) for multiindex, _ in table) != maximum_order:
                raise AssertionError(f"{name} differential order drifted")

        if self.field_pairing.shape != (10, 10) or self.field_pairing.rank() != 10:
            raise AssertionError("endpoint field pairing is degenerate")
        if self.ghost_pairing.shape != (5, 5) or self.ghost_pairing.rank() != 5:
            raise AssertionError("endpoint ghost pairing is degenerate")

        # Every coefficient of C=Y^-1 K^sharp J is checked, including the
        # algebraic Weyl row.  This is the endpoint odd-cyclicity condition.
        for (multiindex, gauge), (other, companion) in zip(
            self.gauge_coefficients,
            self.companion_coefficients,
            strict=True,
        ):
            if multiindex != other:
                raise AssertionError("K/C multiindex orders drifted")
            defect = (
                self.ghost_pairing * companion
                - ((-1) ** sum(multiindex))
                * gauge.T
                * self.field_pairing
            ).applyfunc(sp.expand)
            if defect != sp.zeros(5, 10):
                raise AssertionError("endpoint K/C adjoint defect")

        # The Bach Hessian is action-derived.  In paired coordinates its
        # formal self-adjoint identity is J B=B^sharp J.
        for multiindex, coefficient in self.bach_coefficients:
            defect = (
                self.field_pairing * coefficient
                - ((-1) ** sum(multiindex))
                * coefficient.T
                * self.field_pairing
            ).applyfunc(sp.expand)
            if defect != sp.zeros(10):
                raise AssertionError(
                    f"endpoint Bach adjoint defect at {multiindex}"
                )

        # p_E contains the exact formal adjoint of this S_h.  Reconstructing
        # one from the other guards the inclusion/projection convention.
        reconstructed = _shift_metric_from_projection(
            self.equation_projection_coefficients, self.field_pairing
        )
        if reconstructed != self.shift_metric_coefficients:
            raise AssertionError("endpoint tangent/cotangent graph drifted")

