"""Exact thirty-row endpoint of the curvature-prolonged BV complex.

The hybrid algebraic projector proves that the 386-component mapping
cylinder retracts onto a thirty-component graph.  This module identifies
that graph *coefficientwise*.  It is important that this is not obtained by
relabeling the old 66-by-66 Fourier regression: the endpoint differential is
rebuilt from the actual curved metric gauge generator, the complete
action-normalized linearized Bach operator, and the companion forced by the
curved fibre pairings.

The retained order is

``G_met[5] -> h[10] -> Ebar_met[10] -> I_met[5]``

in degrees ``-1,0,1,2``.  The inclusion into the prolonged carrier is the
local graph

``(i_aux, T_core h, A_core Ebar_met, B_core I_met)``

and the projection is ``p_aux`` after the three forced cotangent corrections
of the mapping cylinder.  No inverse curvature map, Green operator, harmonic
projector, or Fourier-mode splitting occurs.

The module emits every parallel coefficient of ``Q_end`` and every primal
coefficient needed by the graph maps.  Cotangent coefficients are not fitted
again: they are generated by the formal-adjoint rule already certified by
the odd canonical mapping-cylinder kernel.
"""

